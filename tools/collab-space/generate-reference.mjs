import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fromRoot } from '../prototype-cli/project.mjs';
import { loadCollabMap, stagesForTrack, transitionsForTrack, trackOf } from './policy.mjs';

const outputPath = fromRoot('docs', 'generated', 'collab-space-reference.md');
const map = await loadCollabMap();
const actorLabel = new Map(map.actors.map((actor) => [actor.id, actor.label]));
const trackLabel = new Map([
  ['prototype', 'Prototype'],
  ['product-page', 'Product page'],
]);
const tracks = [...new Set(map.stages.map((stage) => trackOf(stage)))];

const lines = [
  '<!-- GENERATED by npm run docs:generate. Edit collab-space.map.yaml, not this file. -->',
  '# Collab Space 正式契約速查',
  '',
  '本頁由 `collab-space.map.yaml` 自動產生。它是角色、階段、資料位置與外部系統邊界的速查表；若本頁與契約不同，`npm run docs:check` 會失敗。',
  '',
  ...tracks.flatMap((track) => [
    '## ' + trackLabel.get(track) + ' track',
    '',
    '```mermaid',
    'flowchart LR',
    ...transitionsForTrack(map, track).map((transition) => '  ' + transition.from.replaceAll('-', '_') + '[' + transition.from + '] -->' + (transition.parallelOutput ? '|parallel output|' : '') + ' ' + transition.to.replaceAll('-', '_') + '[' + transition.to + ']'),
    '```',
    '',
    '### 階段與核准',
    '',
    '| 階段 | 類型 | 可參與角色 | 必要產物 | 離開階段需要 |',
    '|---|---|---|---|---|',
    ...stagesForTrack(map, track).map((stage) => '| `' + stage.id + '` | ' + stage.kind + ' | ' + stage.allowedActors.map((id) => actorLabel.get(id)).join('、') + ' | ' + stage.requiredArtifacts.map((id) => '`' + id + '`').join('、') + ' | ' + stage.exitApprovals.map((id) => actorLabel.get(id)).join('、') + ' |'),
    '',
    ...(track === 'prototype'
      ? ['`rd-handoff` 與 `qa-spec` 是從同一個 `design-final` 版本產生的平行輸出，不會互相等待或改變目前 lifecycle stage。']
      : ['`page-published` 是 `page-strapi-draft` 的平行輸出：自動化只建立 Strapi draft，正式 publish 由人在 Strapi 後台完成。']),
    '',
  ]),
  '## 資料位置與 Owner',
  '',
  '| Artifact | Owner | 位置 | 性質 | 狀態 | Track |',
  '|---|---|---|---|---|---|',
  ...map.artifacts.map((artifact) => '| `' + artifact.id + '` | ' + actorLabel.get(artifact.owner) + ' | `' + artifact.path + '` | ' + artifact.nature + ' | ' + (artifact.status ?? 'active') + ' | ' + trackOf(artifact) + ' |'),
  '',
  '## Workflow 寫入邊界',
  '',
  ...map.workflows.flatMap((workflow) => [
    '### `' + workflow.id + '`',
    '',
    '- Track: `' + trackOf(workflow) + '`',
    '- Actors: ' + workflow.actors.map((id) => actorLabel.get(id)).join('、'),
    '- 可寫入：' + workflow.writablePaths.map((item) => '`' + item + '`').join('、'),
    '- 保護區：' + workflow.protectedPaths.map((item) => '`' + item + '`').join('、'),
    '- Enforcement: `' + workflow.enforcement + '`',
    '',
  ]),
  '## 外部系統邊界',
  '',
  '| 系統 | Owner | 方向 | 可見性 | 可否有 production data |',
  '|---|---|---|---|---|',
  ...map.systems.map((system) => '| `' + system.id + '` | ' + actorLabel.get(system.owner) + ' | ' + system.direction + ' | ' + system.visibility + ' | ' + (system.productionDataAllowed ? '可（僅該外部正式系統）' : '不可') + ' |'),
  '',
  '## 判斷依據',
  '',
  ...map.decisionBasis.map((basis) => '- ' + basis),
  '',
];

const generated = lines.join('\n');
if (process.argv.includes('--check')) {
  const existing = await fs.readFile(outputPath, 'utf8').catch(() => '');
  if (existing !== generated) {
    process.stderr.write('[docs] FAIL generated reference is stale; run npm run docs:generate\n');
    process.exitCode = 1;
  } else process.stdout.write('[docs] PASS generated reference matches contract\n');
} else {
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, generated);
  process.stdout.write('[docs] GENERATED docs/generated/collab-space-reference.md\n');
}
